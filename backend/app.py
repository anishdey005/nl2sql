# Request & Response Models
class QueryRequest(BaseModel):
    prompt: str
    api_key: Optional[str] = None
    model: Optional[str] = GROQ_MODEL
    max_rows: Optional[int] = 200


class VerifyKeyRequest(BaseModel):
    api_key: str


class BenchmarkRequest(BaseModel):
    limit: Optional[int] = 15
    api_key: Optional[str] = None
    category: Optional[str] = None
    difficulty: Optional[str] = None


@app.post("/api/query")
def execute_nl_query(req: QueryRequest):
    """Translates natural language to SQL, validates, executes, and returns results."""
    if not req.prompt.strip():
        raise HTTPException(status_code=400, detail="Query prompt cannot be empty.")

    try:
        result = engine.process_query(
            prompt=req.prompt,
            api_key=req.api_key,
            max_rows=req.max_rows or 200,
            model=req.model or GROQ_MODEL,
        )
        return result
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Query processing failed: {str(e)}")


@app.get("/api/schema")
def get_database_schema():
    """Returns metadata for all 22 tables and foreign key relationships."""
    row_counts = catalog.get_table_row_counts()
    tables_info = []

    for name, meta in TABLE_METADATA.items():
        columns_list = []
        for col_name, col_desc in meta["columns"].items():
            is_pk = "PRIMARY KEY" in col_desc
            is_fk = "FK" in col_desc
            data_type = col_desc.split(" - ")[0] if " - " in col_desc else col_desc
            columns_list.append({
                "name": col_name,
                "type": data_type,
                "description": col_desc,
                "is_primary_key": is_pk,
                "is_foreign_key": is_fk,
            })

        tables_info.append({
            "name": name,
            "description": meta["description"],
            "row_count": row_counts.get(name, 0),
            "columns": columns_list,
            "keywords": meta["keywords"],
        })

    # Format edges for visual graph
    edges = [
        {"source": t1, "target": t2, "on_clause": on}
        for t1, t2, on in FOREIGN_KEY_EDGES
    ]

    return {
        "total_tables": len(TABLE_METADATA),
        "total_records": sum(row_counts.values()),
        "tables": tables_info,
        "relationships": edges,
    }


