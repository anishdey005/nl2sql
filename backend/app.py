@app.post("/api/benchmark/run")
def run_benchmark_endpoint(req: BenchmarkRequest):
    """Runs automated benchmark evaluation on the test suite."""
    try:
        report = evaluator.run_benchmark(
            api_key=req.api_key,
            limit_queries=req.limit or 15,
            category=req.category,
            difficulty=req.difficulty,
        )
        return report
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Benchmark execution failed: {str(e)}")


@app.get("/api/benchmark/latest")
def get_latest_benchmark():
    """Returns the most recent benchmark evaluation report."""
    report_path = os.path.join(PROJECT_ROOT, "backend", "eval", "benchmark_report.json")
    if os.path.exists(report_path):
        import json
        with open(report_path, "r", encoding="utf-8") as f:
            return json.load(f)
    # If not run yet, run default 15
    return evaluator.run_benchmark(limit_queries=15)


@app.post("/api/verify-key")
def verify_groq_key(req: VerifyKeyRequest):
    """Verifies validity of a user-provided Groq API key."""
    if not req.api_key or not req.api_key.startswith("gsk_"):
        return {"valid": False, "message": "Invalid key format. Groq keys typically start with 'gsk_'"}

    try:
        from groq import Groq
        client = Groq(api_key=req.api_key)
        # Test lightweight completion
        resp = client.chat.completions.create(
            model=GROQ_MODEL,
            messages=[{"role": "user", "content": "SELECT 1;"}],
            max_tokens=10,
        )
        return {"valid": True, "message": "Groq API key verified successfully!"}
    except Exception as e:
        return {"valid": False, "message": f"Verification failed: {str(e)}"}


